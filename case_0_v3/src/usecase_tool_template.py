    if not items:
        return ""
    top = max((v for _, v, _ in items if isinstance(v, (int, float))), default=0) or 1
    rows = []
    for label, value, color in items:
        width = max(0.0, min(100.0, 100.0 * (value or 0) / top))
        style = f" style='width:{width:.1f}%;background:{color}'" if color else f" style='width:{width:.1f}%'"
        rows.append(f"<div class='brow'><span class='bl'>{label}</span><span class='bt'><i{style}></i></span><b>{_e(value)}{html.escape(unit)}</b></div>")
    return "<div class='bars'>" + "".join(rows) + "</div>"


