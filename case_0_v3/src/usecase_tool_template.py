# @block sharepoint
def _sp_site(cfg):
    if cfg.get("site_id") and not _is_placeholder(cfg["site_id"]):
        return cfg["site_id"]
    url = cfg.get("site_url", "").replace("https://", "").rstrip("/")
    if not url or _is_placeholder(url):
        raise SourceError("CONFIG_ERROR", "SharePoint site_id or site_url is not configured.")
    host, _, path = url.partition("/")
    cfg["site_id"] = _http("GET", f"{GRAPH}/v1.0/sites/{host}:/{path}", GRAPH_SCOPE).json()["id"]
    return cfg["site_id"]


def _sp_root(site, folder):
    folder = folder.strip("/")
    return f"{GRAPH}/v1.0/sites/{site}/drive/root" + (f":/{quote(folder)}:" if folder else "")


def _sp_list(site, folder):
    url, items = _sp_root(site, folder) + "/children?$top=200&$select=id,name,size,lastModifiedDateTime,file,webUrl", []
    while url:
        doc = _http("GET", url, GRAPH_SCOPE).json()
        items += [i for i in doc.get("value", []) if "file" in i]
        url = doc.get("@odata.nextLink")
    return items


def _sp_download(site, item_id):
    return _http("GET", f"{GRAPH}/v1.0/sites/{site}/drive/items/{item_id}/content", GRAPH_SCOPE).content
# @endblock


# @block source:sharepoint_file
def source_sharepoint_file(src, limit, days):
    site = _sp_site(src)
    pattern = src.get("file") or src.get("pattern") or "*.xlsx"
    try:
        items = _sp_list(site, src.get("folder", ""))
    except SourceError as exc:
        if exc.code == "NOT_FOUND":
            raise SourceError("NOT_FOUND", f"Folder '{src.get('folder', '')}' not found in the SharePoint site.", 404)
        raise
    matches = [i for i in items if fnmatch.fnmatch(i["name"].lower(), pattern.lower())]
    if not matches:
        raise SourceError("NOT_FOUND", f"No file matches '{pattern}' in '{src.get('folder') or '/'}' ({len(items)} files there).")
    item = max(matches, key=lambda i: i.get("lastModifiedDateTime", ""))
    rows = _parse_file(item["name"], _sp_download(site, item["id"]), src)
    return _cap(rows, limit), {"file": item["name"], "file_modified_utc": item.get("lastModifiedDateTime"), "file_url": item.get("webUrl")}
# @endblock


# @block blob
def _blob_url(account, container, name=""):
    return f"https://{account}.blob.core.windows.net/{container}" + (f"/{quote(name)}" if name else "")


def _blob_list(account, container, prefix):
    marker, blobs = "", []
    while True:
        url = _blob_url(account, container) + f"?restype=container&comp=list&prefix={quote(prefix)}" + (f"&marker={quote(marker)}" if marker else "")
        root = ElementTree.fromstring(_http("GET", url, STORAGE_SCOPE, headers={"x-ms-version": "2023-11-03"}).content)
        for blob in root.iter("Blob"):
            modified = blob.findtext("Properties/Last-Modified")
            blobs.append({"name": blob.findtext("Name"), "modified": _iso(parsedate_to_datetime(modified)) if modified else ""})
        marker = root.findtext("NextMarker") or ""
        if not marker:
            return blobs


def _blob_get(account, container, name):
    return _http("GET", _blob_url(account, container, name), STORAGE_SCOPE, headers={"x-ms-version": "2023-11-03"}).content
# @endblock


