def _fmt(value):
    if value is None:
        return "n/d"
    if isinstance(value, bool):
        return str(value)
    if isinstance(value, (int, float)):
        text = f"{value:,.0f}" if float(value).is_integer() else f"{value:,.2f}".rstrip("0").rstrip(".")
        return text.replace(",", "\u202f").replace(".", ",") if CONFIG.get("language", "es") == "es" else text
    return str(value)


def _e(value):
    return html.escape(_fmt(value))


def _label(field):
    labels = CONFIG.get("labels") or {}
    if field in labels:
        return str(labels[field])
    last = str(field).split(".")[-1]
    known = FIELD_LABELS.get(CONFIG.get("language", "es"), {})
    if last.lower() in known:
        return known[last.lower()]
    words = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|[_\-]+", " ", last).split()
    if not words:
        return str(field)
    words = [w if (w.isupper() and len(w) > 1) else w.lower() for w in words]
    text = " ".join(words)
    return text[:1].upper() + text[1:]


