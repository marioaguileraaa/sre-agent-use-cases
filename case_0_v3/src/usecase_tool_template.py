def _rgb(color):
    color = str(color).lstrip("#")
    return tuple(int(color[i:i + 2], 16) for i in (0, 2, 4))


def _hexc(rgb):
    return "#%02x%02x%02x" % tuple(max(0, min(255, int(round(v)))) for v in rgb)


def _mix(a, b, t):
    return _hexc([x + (y - x) * t for x, y in zip(_rgb(a), _rgb(b))])


def _lum(color):
    def channel(v):
        v /= 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (channel(v) for v in _rgb(color))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def _contrast(a, b):
    hi, lo = sorted((_lum(a), _lum(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def _toward(color, target, ratio, against):
    """Mix `color` toward `target` until it reaches `ratio` contrast against `against` (WCAG)."""
    for step in range(21):
        candidate = _mix(color, target, step / 20)
        if _contrast(candidate, against) >= ratio:
            return candidate
    return target


def _rgba(color, alpha):
    r, g, b = _rgb(color)
    return f"rgba({r},{g},{b},{alpha})"


def _hexok(value):
    return isinstance(value, str) and re.match(r"^#[0-9a-fA-F]{6}$", value) is not None


