def _pdf(html_text, path):
    """Print the same HTML to PDF with the headless Chromium that ships with Azure SRE Agent (Playwright)."""
    setting = str(CONFIG.get("pdf", "auto")).lower()
    if setting == "none":
        return "disabled"
    try:
        from playwright.sync_api import sync_playwright
    except Exception as exc:  # noqa: BLE001 - PDF is optional; the HTML report is the source of truth
        return f"skipped: Playwright not available ({type(exc).__name__})"
    wide = any(len(t.get("columns") or []) > 6 for t in CONFIG.get("tables", []))
    landscape = setting == "landscape" or (setting == "auto" and wide)
    client = (CONFIG.get("brand") or {}).get("name") or CONFIG.get("client") or ""
    footer = ("<div style='font-size:7.5px;color:#667085;width:100%;padding:0 12mm;display:flex;justify-content:space-between;font-family:sans-serif'>"
              f"<span>{html.escape((client + ' · ') if client else '')}{html.escape(CONFIG['title'])}</span>"
              f"<span>{_dt('page')} <span class='pageNumber'></span> / <span class='totalPages'></span></span></div>")
    try:
        with sync_playwright() as pw:
            browser, last = None, None
            for options in ({}, {"channel": "msedge"}, {"channel": "chrome"}):
                try:
                    browser = pw.chromium.launch(**options)
                    break
                except Exception as exc:  # noqa: BLE001
                    last = exc
            if browser is None:
                return f"skipped: no Chromium available ({type(last).__name__})"
            try:
                page = browser.new_page(viewport={"width": 1280, "height": 900})
                page.route(re.compile(r"^https?://"), lambda route: route.abort())
                page.set_content(html_text, wait_until="load")
                page.emulate_media(media="print")
                page.pdf(path=str(path), format="A4", landscape=landscape, print_background=True,
                         margin={"top": "12mm", "bottom": "14mm", "left": "10mm", "right": "10mm"},
                         display_header_footer=True, header_template="<span></span>", footer_template=footer)
            finally:
                browser.close()
        return "OK"
    except Exception as exc:  # noqa: BLE001
        return f"skipped: {type(exc).__name__}: {str(exc)[:160]}"


