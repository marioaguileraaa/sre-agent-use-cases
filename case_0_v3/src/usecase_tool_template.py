def _write_outputs(ctx, snapshot):
    root = Path.cwd()
    folder = root / CONFIG["tool_name"]
    folder.mkdir(parents=True, exist_ok=True)
    stamp = ctx["now"].strftime("%Y%m%dT%H%M%SZ")
    prefix = ("selftest-" if ctx["simulated"] else "") + CONFIG.get("file_prefix", CONFIG["tool_name"])
    html_path, json_path, csv_path = (folder / f"{prefix}-{stamp}.html", folder / f"{prefix}-{stamp}.json", folder / f"{prefix}-{stamp}-findings.csv")
    html_text = _html(ctx)
    html_path.write_text(html_text, encoding="utf-8")
    pdf_path = folder / f"{prefix}-{stamp}.pdf"
    ctx["pdf"] = _pdf(html_text, pdf_path)
    files = [html_path] + ([pdf_path] if ctx["pdf"] == "OK" and pdf_path.exists() else []) + [json_path, csv_path]
    json_path.write_text(json.dumps({"summary": ctx["summary"], "comparison": ctx["diff"], "snapshot": snapshot}, ensure_ascii=False, indent=1, default=str), encoding="utf-8")
    with csv_path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["severity", "rule", "title", "item", "message"])
        for f in ctx["findings"]:
            writer.writerow([f["severity"], f["rule"], f["title"], f["item"], f["message"]])
    for name, rows in ctx["data"].items():
        if not rows:
            continue
        path = folder / f"{prefix}-{stamp}-{re.sub(r'[^a-zA-Z0-9_-]', '_', name)}.csv"
        fields = list(dict.fromkeys(k for r in rows[:2000] for k in r))
        with path.open("w", encoding="utf-8-sig", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
            writer.writeheader()
            writer.writerows(rows)
        files.append(path)
    match = re.search(r"/tmp/ThreadFiles/([0-9a-fA-F-]{36})", root.as_posix())
    links = {p.name: (f"/api/files/tmp/ThreadFiles/{match.group(1)}/{quote(CONFIG['tool_name'])}/{quote(p.name)}" if match else str(p)) for p in files}
    return files, links, stamp, len(files) - len([n for n, r in ctx["data"].items() if r])


