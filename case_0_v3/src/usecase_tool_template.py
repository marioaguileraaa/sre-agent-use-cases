def _tokens(name):
    return [t.lower() for t in re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+|\d+", str(name))]


def _synthetic_guess(name, i, now):
    tokens = set(_tokens(name))
    if tokens & SYN_NUMBER and not tokens & {"vm", "sku", "type", "tier", "name", "by", "id", "zone", "version"}:
        return round([0.4, 2.5, 7, 18, 45, 120][i] * (24 if tokens & {"hours", "hour"} else 1), 1)
    if tokens & SYN_DATE and not tokens & {"by", "user", "owner", "caller", "principal", "name", "upn", "email", "zone", "type", "format", "id"}:
        return _iso(now - timedelta(hours=[2, 30, 75, 160, 300, 900][i]))
    if "resource" in tokens and "id" in tokens:
        return f"/subscriptions/00000000-0000-0000-0000-000000000000/resourceGroups/rg-demo-{'aab'[i % 3]}/providers/Microsoft.Compute/virtualMachines/vm-demo-{i + 1:02d}"
    if "id" in tokens and tokens & {"subscription", "tenant", "app", "object", "client", "principal"}:
        return f"{'a1b2c3d4e5f6'[i] * 8}-0000-4000-8000-{i + 1:012d}"
    if tokens & {"os", "platform"}:
        return ["Windows", "Linux", "Windows", "Linux", "Windows", "Windows"][i]
    if tokens & {"location", "region"}:
        return ["westeurope", "northeurope", "westeurope", "spaincentral", "westeurope", "northeurope"][i]
    if "currency" in tokens:
        return "EUR"
    return None


def _synthetic_other(name):
    return "OK" if set(_tokens(name)) & SYN_STATUS else ("Otro" if CONFIG.get("language") == "es" else "Other")


def _synthetic_spread(points):
    ts = sorted(points)
    low = ts[0] - abs(ts[0]) * 0.5 - (1 if ts[0] == 0 else 0)
    high = [ts[-1] * f + (1 if ts[-1] == 0 else 0) for f in (1.1, 1.5, 2.5)]
    core = [low] + [(a + b) / 2 for a, b in zip(ts, ts[1:])] + high[:1]
    values = core + high[1:] + [low - abs(low) * 0.5]
    values = values[:6] if len(core) <= 6 else core[:5] + high[:1]
    return [round(v, 2) for v in values]


def _synthetic(src, now):
    if src.get("sample_rows"):
        return [dict(r) for r in src["sample_rows"]]
    fields, rows, thresholds = {}, [], {}
    for rule in CONFIG.get("rules", []) + [{"dataset": k["dataset"], "when": k.get("where")} for k in CONFIG.get("kpis", [])]:
        if rule["dataset"] != src["id"]:
            continue
        stack = [rule.get("when") or {}]
        while stack:
            c = stack.pop()
            stack += c.get("all", []) + c.get("any", []) + ([c["not"]] if "not" in c else [])
            if c.get("field") and c.get("op") in ("gt", "gte", "lt", "lte") and _num(c.get("value")) is not None:
                thresholds.setdefault(c["field"], set()).add(_num(c.get("value")))
            if c.get("field"):
                prev = fields.get(c["field"])
                if prev and prev.get("op") in ("in", "eq") and c.get("op") in ("in", "eq"):
                    values = lambda x: list(x["value"]) if isinstance(x.get("value"), list) else [x.get("value")]
                    fields[c["field"]] = {"op": "in", "value": list(dict.fromkeys(values(prev) + values(c)))}
                else:
                    fields.setdefault(c["field"], c)
    for key in (CONFIG.get("keys") or {}).get(src["id"], []):
        fields.setdefault(key, {"op": "key"})
    for k in CONFIG.get("kpis", []):
        if k["dataset"] == src["id"] and k.get("field"):
            fields.setdefault(k["field"], {"op": "gt", "value": 10} if k.get("agg", "count") not in ("count", "distinct") else {"op": "key"})
    for c in CONFIG.get("charts", []):
        if c["dataset"] == src["id"]:
            fields.setdefault(c["by"], {"op": "group"})
            if c.get("field") and c.get("agg", "count") not in ("count", "distinct"):
                fields.setdefault(c["field"], {"op": "gt", "value": 100})
    for t in CONFIG.get("tables", []):
        if t["dataset"] == src["id"]:
            for col in t.get("columns", []):
                fields.setdefault(col, {"op": "text"})
    for rule in CONFIG.get("rules", []):
        if rule["dataset"] == src["id"]:
            for ref in re.findall(r"\{([^{}]+)\}", rule.get("message") or ""):
                fields.setdefault(ref.strip(), {"op": "text"})
    derived = {d["name"]: d for d in CONFIG.get("derive", []) if d["dataset"] == src["id"]}
    for name in list(fields):
        if name in derived:
            spec, cond = derived[name], fields.pop(name)
            limit = _num(cond.get("value")) or 30
            sign = 1 if spec["type"] == "days_until" else -1
            fields[spec["field"]] = {"op": "derived", "days": [sign * limit * f for f in (-0.5, 0.3, 0.9, 1.2, 2, 4)]}
    for d in derived.values():
        fields.setdefault(d["field"], {"op": "derived", "days": [(1 if d["type"] == "days_until" else -1) * x for x in (-5, 3, 12, 25, 60, 120)]})
    for i in range(6):
        row = {}
        for name, c in fields.items():
            op, val = c.get("op"), c.get("value")
            guess = _synthetic_guess(name, i, now) if op in ("text", "group", None) else None
            if op == "derived":
                row[name] = _iso(now + timedelta(days=c["days"][i]))
            elif op in ("expired", "expires_within_days", "older_than_days", "newer_than_days"):
                row[name] = _iso(now + timedelta(days=[-5, 3, 12, 25, 60, 120][i] * (-1 if op in ("older_than_days", "newer_than_days") else 1)))
            elif op in ("gt", "gte", "lt", "lte") and len(thresholds.get(name, ())) > 1:
                row[name] = _synthetic_spread(thresholds[name])[i]
            elif op in ("gt", "gte", "lt", "lte"):
                row[name] = round((_num(val) or 10) * [0.2, 0.6, 0.9, 1.1, 1.5, 2.5][i], 2)
            elif op in ("in", "not_in"):
                row[name] = (list(val) + [_synthetic_other(name)])[i % (len(val) + 1)]
            elif op in ("eq", "ne"):
                row[name] = val if i % 2 == 0 else _synthetic_other(name)
            elif guess is not None:
                row[name] = guess
            elif op == "key":
                row[name] = f"{name}-{i + 1:02d}"
            elif op == "group":
                row[name] = f"{name}-{'ABCAAB'[i]}"
            elif op == "contains":
                row[name] = f"{name}-{i + 1:02d} {val}" if i % 2 == 0 else f"{name}-{i + 1:02d}"
            elif op == "not_empty":
                row[name] = f"{name}-{i + 1:02d}" if i % 2 == 0 else ""
            elif op == "empty":
                row[name] = "" if i % 2 == 0 else f"{name}-{i + 1:02d}"
            else:
                row[name] = f"{name}-{i + 1:02d}"
        rows.append(row or {"item": f"item-{i + 1:02d}", "value": i})
    return rows


def _selftest_collect(src, now):
    rows = _synthetic(src, now)
    if src["type"] in ("sharepoint_file", "blob_file"):
        pattern = (src.get("file") or src.get("pattern") or "").lower()
        if pattern.endswith((".xlsx", ".xlsm")) or "xls" in pattern or not pattern:
            from openpyxl import Workbook
            book, buffer = Workbook(), io.BytesIO()
            sheet = book.active
            sheet.title = src.get("sheet") or "Sheet1"
            cols = list(dict.fromkeys(k for r in rows for k in r))
            for _ in range(int(src.get("header_row", 1)) - 1):
                sheet.append([None])
            sheet.append(cols)
            for r in rows:
                sheet.append([r.get(c) for c in cols])
            book.save(buffer)
            rows = _parse_file("selftest.xlsx", buffer.getvalue(), src)
        else:
            text = io.StringIO()
            cols = list(dict.fromkeys(k for r in rows for k in r))
            writer = csv.DictWriter(text, fieldnames=cols)
            writer.writeheader()
            writer.writerows(rows)
            rows = _parse_file("selftest.csv", text.getvalue().encode(), src)
    return rows, {"file": "selftest (synthetic)"} if src["type"] in ("sharepoint_file", "blob_file") else {}


def _selftest_previous(data, now):
    previous = {}
    for name, rows in data.items():
        if rows is None:
            continue
        rows = [dict(r) for r in rows[:-1]]
        if rows:
            first = rows[0]
            for field, value in first.items():
                if _num(value) is not None and not str(field).startswith("_"):
                    first[field] = round(_num(value) * 0.8, 2)
                    break
            gone = dict(rows[-1])
            for k in (CONFIG.get("keys") or {}).get(name, []):
                gone[k] = f"{gone.get(k)}-retired"
            rows.append(gone)
        previous[name] = rows
    earlier = now - timedelta(days=7)
    _derive(previous, earlier)
    kpis = _kpis(previous, earlier)
    found, _ = _findings(previous, earlier)
    return _snapshot(previous, kpis, found, earlier)


